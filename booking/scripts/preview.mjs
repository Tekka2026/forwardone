// Builds the dashboard preview on the site (public/the-pitch/review-preview/)
// from src/review.ts itself, with invented sample data and a local stand-in
// for the API, so the preview always matches the real dashboard.
// Usage: node --experimental-strip-types scripts/preview.mjs [fragment-out.html]
import { writeFileSync, mkdirSync } from 'node:fs';
import { BUSY_JS, CLIENT_JS, CSS, FONTS, dashboardHtml, loginHtml } from '../src/review.ts';

const at = (h, m) => `2026-10-26T${String(h).padStart(2, '0')}:${String(m).padStart(2, '0')}:00.000Z`;
const slots = ['14:00', '14:10', '14:20', '14:30', '14:40', '14:50'].map((label) => ({ id: label.replace(':', ''), label }));
const app = (id, label, status, company, building, name, role, email, created, extra = {}) => ({
  id, slot_id: label.replace(':', ''), label, status, company, building, name, role, email,
  phone: null, deck: 'https://example.com/deck.pdf', created_at: created, decided_by: null, ...extra,
});
const data = {
  event: 'The _____ Pitch at Slush',
  who: 'you@forward.one',
  emailConfigured: true,
  pageUrl: 'https://tekka2026.github.io/forwardone/the-pitch/',
  slots,
  apps: [
    app('a1', '14:00', 'pending', 'Northwind Robotics', 'robots that fold laundry', 'Ann Example', 'CEO', 'ann@northwind.example', at(8, 12)),
    app('a2', '14:20', 'approved', 'Lumen Labs', 'batteries from seaweed', 'Bo Sample', 'Founder', 'bo@lumen.example', at(9, 40), { phone: '+358 40 000 0000', decided_by: 'reviewer@forward.one' }),
    app('a3', '14:30', 'pending', 'Quill', 'contracts that read themselves', 'Cy Demo', 'CTO', 'cy@quill.example', at(10, 3), { deck: null }),
    app('a4', '14:50', 'pending', 'Fjord Sensors', 'wind turbine blades that report their own cracks', 'Dee Placeholder', 'CEO', 'dee@fjord.example', at(10, 31)),
    app('a5', '14:10', 'denied', 'Tundra Foods', 'protein from forest fungi', 'Eli Test', 'Founder', 'eli@tundra.example', at(7, 55), { decided_by: 'reviewer@forward.one' }),
  ],
};

const notice = '<p class="banner banner--neutral">Preview with invented sample applicants. Login, Approve and Deny work on this page only: nothing is sent or saved, and any email address gets in.</p>';
const body = `${notice}
<div id="login-view">${loginHtml(data.event)}
  <div class="banner banner--ok" id="login-sent" hidden>
    <p class="flush">If <b id="login-to"></b> may review, a login link is on its way. In this preview no email is sent.</p>
    <p class="flush"><button class="btn btn--sm" type="button" id="login-open">Open the login link</button></p>
  </div>
</div>
<div id="dash-view" class="stack" hidden>${dashboardHtml(data, false)}</div>
<script>
window.REVIEW_API = { decide: function () { return new Promise(function (ok) { setTimeout(function () { ok({ ok: true }); }, 450); }); } };
(function () {
  var form = document.querySelector('#login-view form');
  form.addEventListener('submit', function (e) {
    e.preventDefault();
    var email = form.querySelector('input[type=email]').value.trim();
    setTimeout(function () {
      var b = form.querySelector('[type=submit]'); b.disabled = false; b.textContent = 'Send me a link';
      document.getElementById('login-to').textContent = email;
      document.getElementById('login-sent').hidden = false;
      document.getElementById('login-open').focus();
    }, 450);
  });
  function show(dash) {
    document.getElementById('login-view').hidden = dash;
    document.getElementById('dash-view').hidden = !dash;
  }
  document.getElementById('login-open').addEventListener('click', function () {
    var who = document.getElementById('login-to').textContent;
    document.querySelector('#dash-view .who span').textContent = who;
    show(true);
  });
  document.getElementById('logout').addEventListener('click', function () {
    form.reset(); document.getElementById('login-sent').hidden = true; show(false);
  });
})();
</script>
<script>${CLIENT_JS}</script>`;

const extraCss = '.stack { display: grid; grid-template-columns: minmax(0, 1fr); gap: 24px; } .stack[hidden], #login-view[hidden] { display: none; } #login-view { display: grid; gap: 16px; }';
const title = 'The Pitch review';
const full = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<meta name="robots" content="noindex, nofollow">
<!-- Generated by booking/scripts/preview.mjs from booking/src/review.ts; sample data only. -->
<title>${title}</title>
${FONTS}
<style>${CSS}${extraCss}</style>
</head>
<body><main>${body}</main></body>
</html>
`;
const out = new URL('../../public/the-pitch/review-preview/', import.meta.url);
mkdirSync(out, { recursive: true });
writeFileSync(new URL('index.html', out), full);
console.log('preview: public/the-pitch/review-preview/index.html');
if (process.argv[2]) {
  // The same page without the document skeleton (for a claude.ai artifact).
  writeFileSync(process.argv[2], `<title>${title}</title>\n<meta name="claude:viewport-fit-sides" content="cover">\n${FONTS}\n<style>${CSS}${extraCss}</style>\n<main>${body}</main>\n`);
  console.log('fragment:', process.argv[2]);
}
