// Turns the built /the-pitch page (dist/the-pitch/index.html, after
// `npm run build`) into three pieces of code for a Webflow page (A0019):
//   head.html   -> Page settings > Custom code > Inside <head> tag
//   embed.html  -> a Code Embed element on the page (the markup)
//   footer.html -> Page settings > Custom code > Before </body> tag (the script)
// Each piece stays under Webflow's 50,000-character limit per code field.
// Usage: npm run build && node webflow/export.mjs
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';

const BASE = '/forwardone';
const LIMIT = 50000;
const root = new URL('..', import.meta.url);
const read = (p) => readFileSync(new URL(p, root), 'utf8');
const html = read('dist/the-pitch/index.html');

// Stylesheets the page links to, from the build output, in order.
const css = [...html.matchAll(/<link rel="stylesheet" href="(\/forwardone\/_astro\/[^"]+\.css)">/g)]
  .map((m) => read('dist' + m[1].slice(BASE.length)))
  .join('\n')
  // Geist Mono comes from Google Fonts on Webflow (the self-hosted files stay on GitHub Pages).
  .replace(/@font-face\{font-family:Geist Mono;[^}]*\}/g, '');

const fonts = [
  'https://fonts.googleapis.com/css2?family=Inter:wght@400..600&family=Geist+Mono:wght@400;500&family=Covered+By+Your+Grace&display=swap',
];
const head = [
  '<!-- The ____ Pitch: fonts and styles (generated by webflow/export.mjs) -->',
  '<link rel="preconnect" href="https://fonts.googleapis.com">',
  '<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>',
  ...fonts.map((f) => `<link rel="stylesheet" href="${f}">`),
  // One rule per line, so the file is readable when opened.
  `<style>\n${css.replace(/\}(?!\s*\n)/g, '}\n')}</style>`,
].join('\n');

// Body: markup for the embed, scripts for the footer field. Internal links
// lose the GitHub Pages base path ("/forwardone/" -> "/").
// Scripts may sit in the head (Astro hoists page scripts), so take them
// from the whole document.
const scripts = [...html.matchAll(/<script\b[^>]*>([\s\S]*?)<\/script>/g)].map((m) => m[1].trim());
let body = html.slice(html.indexOf('>', html.indexOf('<body')) + 1, html.lastIndexOf('</body>'));
body = body.replace(/<script\b[^>]*>[\s\S]*?<\/script>/g, '');
body = body.replace(/(href|src)="\/forwardone\//g, '$1="/');

const embed = `<!-- The ____ Pitch: page markup (generated by webflow/export.mjs) -->\n${body.trim()}`;
const footer = `<!-- The ____ Pitch: behaviour (generated by webflow/export.mjs) -->\n${scripts.map((s) => `<script>\n${s}\n</script>`).join('\n')}`;

const out = new URL('webflow/the-pitch/', root);
mkdirSync(out, { recursive: true });
for (const [name, text] of [['head.html', head], ['embed.html', embed], ['footer.html', footer]]) {
  if (text.length > LIMIT) throw new Error(`${name} is ${text.length} characters, over Webflow's ${LIMIT}`);
  writeFileSync(new URL(name, out), text + '\n');
  // The same as plain text: opened in a browser, head.html alone shows a
  // blank page (it holds only fonts and styles); the .txt shows the code.
  writeFileSync(new URL(name.replace('.html', '.txt'), out), text + '\n');
  console.log(name.padEnd(12), text.length, 'characters');
}
